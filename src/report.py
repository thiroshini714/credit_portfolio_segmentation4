"""Generate a markdown analysis report from the pipeline results.

The numbers in the report come straight from the run, so when the real
dataset is used the report documents the real findings.
"""

import numpy as np
import pandas as pd

from src.insights import ETHICS_NOTE


def _cell(value, decimals=3):
    if isinstance(value, (float, np.floating)):
        return "n/a" if np.isnan(value) else f"{value:,.{decimals}f}"
    return str(value)


def to_markdown(df, decimals=3):
    """Small markdown table writer (avoids the optional tabulate package)."""
    if df is None or len(df) == 0:
        return "_No data._\n"
    header = "| " + " | ".join(str(c) for c in df.columns) + " |"
    divider = "| " + " | ".join("---" for _ in df.columns) + " |"
    rows = ["| " + " | ".join(_cell(v, decimals) for v in row) + " |"
            for row in df.itertuples(index=False)]
    return "\n".join([header, divider] + rows) + "\n"


def write_report(results, path):
    """Write ``analysis_report.md`` and return the text."""
    meta, clean = results["metadata"], results["cleaning"]
    lines = ["# Credit Portfolio Segmentation - Analysis Report", "",
             "_Auto-generated by the pipeline from the latest run._", ""]
    if meta.get("data_is_synthetic", False):
        lines += ["> **SYNTHETIC DATA NOTICE:** This report uses simulated loan "
                  "records. Its metrics, default rates, cluster profiles, "
                  "geographic patterns and recommendations are for software "
                  "demonstration only and are not real-world credit findings.", ""]

    lines += ["## 1. Data and preprocessing", "",
              f"- Source file: `{meta['data_file']}`",
              f"- Raw rows: {clean['rows_raw']:,}; rows after cleaning: "
              f"{clean['rows_final']:,}",
              f"- Duplicate rows removed: {clean['duplicate_rows_removed']:,}; "
              f"duplicate IDs removed: {clean['duplicate_ids_removed']:,}",
              f"- Impossible values set to missing: "
              f"{clean['invalid_values_set_missing']}",
              f"- Missing values before imputation: "
              f"{clean['missing_before_imputation']}",
              f"- Imputation: {clean['imputation_strategy']}",
              f"- Log-transformed (skewed) features: "
              f"{meta['log_transformed']}",
              f"- Rows used for clustering: {meta['rows_clustered']:,} "
              f"(random seed {meta['random_state']})", ""]
    if clean.get("overall_default_rate") is not None:
        lines.append(f"- Portfolio default rate (known outcomes, "
                     f"{clean['default_known_rows']:,} loans): "
                     f"{100 * clean['overall_default_rate']:.2f}%")
        lines.append("")

    lines += ["### Outlier summary (IQR rule)", "",
              to_markdown(results["outliers"], 2),
              "### Descriptive statistics", "",
              to_markdown(results["eda_summary"]["describe"], 2),
              "Strongest feature correlations: "
              f"{results['eda_summary']['strongest_correlations']}", ""]

    pca = results["pca_info"]
    lines += ["## 2. Dimensionality reduction", "",
              f"- PCA: {pca['n_components']} of {pca['n_features']} "
              f"components retain {100 * pca['variance_retained']:.1f}% of "
              f"variance (PC1+PC2 = {100 * pca['variance_pc12']:.1f}%).",
              f"- t-SNE computed: {meta['tsne_computed']}; UMAP computed: "
              f"{meta['umap_computed']}", ""]

    lines += ["## 3. Clustering", "",
              f"K-Means k = {meta['kmeans_k']} (best silhouette with "
              f"k >= 3).", "", "### K-Means search", "",
              to_markdown(results["k_table"]),
              "### Algorithm comparison", "",
              to_markdown(results["comparison"].drop(columns=["key"])),
              "### Hierarchical linkage comparison (subsample)", "",
              to_markdown(results["linkage_table"]),
              f"DBSCAN settings: {meta['dbscan']}", ""]

    profile = results["profile"]
    keep = [c for c in ("cluster", "segment", "size", "pct_of_portfolio",
                        "median_annual_inc", "median_fico", "median_dti",
                        "median_loan_amnt", "median_emp_length",
                        "top_purpose", "top_home_ownership", "default_rate")
            if c in profile.columns]
    lines += ["## 4. Cluster profiles (K-Means)", "",
              to_markdown(profile[keep], 2)]

    default = results["default"]
    if len(default):
        lines += ["## 5. Historical default rates by segment", "",
                  to_markdown(default[[
                      "cluster", "segment", "n_with_outcome", "n_defaults",
                      "default_rate", "ci_low", "ci_high",
                      "lift_vs_portfolio", "risk_tier"]], 3)]
        chi = results["chi2"]
        if chi:
            lines.append(f"Chi-square: {chi}")
            lines.append("")

    anomaly = results["anomaly"]
    lines += ["## 6. Anomalies", "",
              f"- Flagged: {anomaly['n_anomalies']:,} of "
              f"{anomaly['n_total']:,} ({anomaly['pct_anomalies']:.1f}%)",
              f"- DBSCAN noise: {anomaly['n_dbscan_noise']:,}; extreme "
              f"feature: {anomaly['n_feature_extreme']:,}", "",
              to_markdown(anomaly["by_type"], 0)]

    lines += ["## 7. Business insights", ""]
    for item in results["insights"]:
        lines.append(f"- **{item['title']}** - {item['detail']}")
    lines += ["", "### Segment recommendations", ""]
    if results["recommendations"]:
        lines.append(to_markdown(
            pd.DataFrame(results["recommendations"])[[
                "segment", "risk_tier", "default_rate",
                "share_of_portfolio_pct", "recommendation"]], 3))
    lines += ["", "## 8. Ethical use", "", ETHICS_NOTE, ""]

    text = "\n".join(lines)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    return text
